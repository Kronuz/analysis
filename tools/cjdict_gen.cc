// Builds the dictionary include from ICU's cjdict.txt at build time: each word's
// characters become dense ids (the most frequent in one byte, the rest in two), and an
// FST maps the id-encoded words to their costs.
//
//   cjdict_gen data/cjdict.txt cjdict.inc
//
// The text is parsed as ICU's gendict parses it: '#' starts a comment, trailing spaces
// go, a word runs to the first space, and its value is the rest (strtoul, base 0).
#include "fst.hh"
#include "staged.hh"

#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <map>
#include <sstream>
#include <string>
#include <vector>

namespace {

[[noreturn]] void fail(const std::string& what) {
	std::fprintf(stderr, "cjdict_gen: %s\n", what.c_str());
	std::exit(1);
}

bool is_space(char c) { return c == ' ' || c == '\t' || c == '\r' || c == '\n' || c == '\v' || c == '\f'; }

// Strict UTF-8: the dictionary is valid text, and anything else is a broken input file.
std::u32string decode(const std::string& s, std::size_t line) {
	std::u32string out;
	for (std::size_t i = 0; i < s.size();) {
		const auto b = static_cast<unsigned char>(s[i]);
		const std::size_t n = b < 0x80 ? 1 : (b >> 5) == 6 ? 2 : (b >> 4) == 14 ? 3 : (b >> 3) == 30 ? 4 : 0;
		if (n == 0 || i + n > s.size()) { fail("invalid UTF-8 on line " + std::to_string(line)); }
		char32_t c = n == 1 ? b : b & (0x7F >> n);
		for (std::size_t k = 1; k < n; ++k) {
			const auto x = static_cast<unsigned char>(s[i + k]);
			if ((x & 0xC0) != 0x80) { fail("invalid UTF-8 on line " + std::to_string(line)); }
			c = (c << 6) | (x & 0x3F);
		}
		if (c > 0x10FFFF || (c >= 0xD800 && c <= 0xDFFF)) { fail("invalid code point on line " + std::to_string(line)); }
		out.push_back(c);
		i += n;
	}
	return out;
}

}  // namespace

int main(int argc, char** argv) {
	if (argc != 3) { fail("usage: cjdict_gen CJDICT_TXT OUT_INC"); }
	std::ifstream in(argv[1], std::ios::binary);
	if (!in) { fail(std::string("cannot read ") + argv[1]); }
	std::vector<std::pair<std::u32string, std::uint64_t>> words;
	std::map<char32_t, std::size_t> freq;
	std::string line;
	for (std::size_t n = 1; std::getline(in, line); ++n) {
		if (n == 1 && line.rfind("\xEF\xBB\xBF", 0) == 0) { line.erase(0, 3); }
		if (auto hash = line.find('#'); hash != std::string::npos) { line.erase(hash); }
		while (!line.empty() && is_space(line.back())) { line.pop_back(); }
		if (line.empty()) { continue; }
		std::size_t key = 0;
		while (key < line.size() && !is_space(line[key])) { ++key; }
		if (key == 0) { fail("no word on line " + std::to_string(n)); }
		std::size_t value = key;
		while (value < line.size() && is_space(line[value])) { ++value; }
		std::uint64_t v = 0;
		if (value < line.size()) {
			const std::string text = line.substr(value);
			char* end = nullptr;
			v = std::strtoul(text.c_str(), &end, 0);
			if (end == text.c_str() || *end || v > 0xFFFFFFFF) { fail("bad value on line " + std::to_string(n)); }
		}
		std::u32string w = decode(line.substr(0, key), n);
		for (char32_t c : w) { ++freq[c]; }
		words.emplace_back(std::move(w), v);
	}

	// Dense ids, most frequent first (ties by code point). Ids below `single` take one
	// byte; the rest take a lead byte in [single, 256) and a trail byte.
	std::vector<std::pair<std::size_t, char32_t>> order;
	for (auto& [c, f] : freq) { order.emplace_back(f, c); }
	std::sort(order.begin(), order.end(), [](auto& a, auto& b) { return a.first != b.first ? a.first > b.first : a.second < b.second; });
	if (order.size() > 0xFFFF - 255) { fail("too many distinct characters"); }
	const unsigned single = unsigned((0x10000 - order.size()) / 255);
	std::vector<std::uint16_t> id(0x110000, 0xFFFF);
	for (std::size_t i = 0; i < order.size(); ++i) { id[order[i].second] = std::uint16_t(i); }

	std::map<std::string, std::uint64_t> keys;
	for (auto& [w, v] : words) {
		std::string k;
		for (char32_t c : w) {
			const unsigned i = id[c];
			if (i < single) {
				k.push_back(char(i));
			} else {
				k.push_back(char(single + ((i - single) >> 8)));
				k.push_back(char((i - single) & 0xFF));
			}
		}
		if (!keys.emplace(std::move(k), v).second) { fail("duplicate word"); }
	}
	fst::builder b;
	for (auto& [k, v] : keys) { b.insert(k, v); }
	const std::string bytes = b.finish();

	std::ostringstream out;
	out << "// Generated by tools/cjdict_gen.cc from data/cjdict.txt (" << keys.size() << " words). Do not edit.\n";
	out << "// ICU's Chinese/Japanese dictionary: BSD and Unicode-3.0, see LICENSE-ICU.\n";
	out << "namespace analysis::cjk::dictionary {\n\n";
	out << "inline constexpr std::size_t words = " << keys.size() << ";\n";
	out << "inline constexpr unsigned single_byte_ids = " << single << ";  // ids below take one byte\n";
	out << "inline constexpr std::uint16_t no_id = 0xFFFF;\n";
	out << "// Each code point's id; no_id when no word contains it.\n" << staged::print("id", staged::build(id), "std::uint16_t");
	out << "inline constexpr std::size_t fst_size = " << bytes.size() << ";\n";
	out << "alignas(16) inline constexpr char fst_bytes[] =";
	static const char* const hex = "0123456789abcdef";
	for (std::size_t i = 0; i < bytes.size(); ++i) {
		if (i % 64 == 0) { out << "\n\t\""; }
		const auto c = static_cast<unsigned char>(bytes[i]);
		out << '\\' << 'x' << hex[c >> 4] << hex[c & 15];
		if (i % 64 == 63 || i + 1 == bytes.size()) { out << '"'; }
	}
	out << ";\n\n}  // namespace analysis::cjk::dictionary\n";

	std::ofstream o(argv[2], std::ios::binary);
	o << out.str();
	if (!o) { fail(std::string("cannot write ") + argv[2]); }
	return 0;
}
